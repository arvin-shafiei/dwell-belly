// Builds apps/web/src/world/scenarios.data.ts from data/cases/delivery: one scenario per public case,
// each mapped to a "scene" the 3D city can act out. Run: node scripts/build-scenarios.mjs
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
// case number -> [scene, where]. scene = what the city shows; where = roughly where it happens.
const SCENES = {
  "001": ["door_slot_change", "suburbs"], "002": ["address_incomplete", "downtown"], "003": ["access_gated", "suburbs"],
  "004": ["call_before_arrival", "suburbs"], "005": ["alternate_recipient", "suburbs"], "006": ["pickup_point", "downtown"],
  "007": ["pickup_point", "downtown"], "008": ["door_slot_change", "suburbs"], "009": ["bulky_access", "suburbs"],
  "010": ["hold_delivery", "depot"], "011": ["tracking_stale", "depot"], "012": ["vehicle_breakdown", "road"],
  "013": ["failed_attempt_dispute", "suburbs"], "014": ["business_closed", "downtown"], "015": ["misrouted_depot", "depot"],
  "016": ["locker_full", "downtown"], "017": ["notification_broken", "office"], "018": ["return_deadline", "depot"],
  "019": ["severe_weather", "road"], "020": ["partial_delivery", "suburbs"], "021": ["damage_evidence", "suburbs"],
  "022": ["damage_confirmed", "suburbs"], "023": ["leaking_parcel", "depot"], "024": ["delivered_not_received", "suburbs"],
  "025": ["lost_parcel", "depot"], "026": ["misdelivered_neighbour", "suburbs"], "027": ["misdelivered_wrong_customer", "suburbs"],
  "028": ["wrong_item", "suburbs"], "029": ["cold_chain_breach", "road"], "030": ["pod_missing_high_value", "downtown"],
  "031": ["return_label_missing", "suburbs"], "032": ["return_label_printer", "downtown"], "033": ["return_collection_missed", "suburbs"],
  "034": ["return_stuck_depot", "depot"], "035": ["refund_review_stalled", "office"], "036": ["business_collection", "downtown"],
  "037": ["heavy_item_collection", "suburbs"], "038": ["returned_to_sender", "depot"], "039": ["duplicate_shipment", "suburbs"],
  "040": ["cancel_before_dispatch", "depot"], "041": ["pallet_no_appointment", "downtown"], "042": ["pallet_no_forklift", "downtown"],
  "043": ["freight_dimensions", "docks"], "044": ["pallet_missing", "downtown"], "045": ["customs_invoice", "docks"],
  "046": ["customs_broker", "docks"], "047": ["import_charge", "docks"], "048": ["customs_last_mile", "docks"],
  "049": ["billing_duplicate", "office"], "050": ["guarantee_refund", "office"],
};

const out = [];
for (let n = 1; n <= 50; n++) {
  const num = String(n).padStart(3, "0");
  const c = JSON.parse(await readFile(path.join(ROOT, "data/cases/delivery", `${num}.json`), "utf8"));
  const last = c.escalation_snapshot?.last_event ?? 2;
  const [scene, where] = SCENES[num];
  out.push({
    id: `delivery-${num}`,
    title: c.title.replace(/^Case \d+: /, ""),
    scene,
    where,
    shipment: c.details.primary_shipment ?? c.details.primary_task_reference ?? null,
    context: c.context,
    request: c.initial_request,
    // What the agent sees at escalation (no answer leaked into the inputs)
    messages: c.events.filter((e) => e.n <= last).map((e) => ({ channel: e.channel, from: e.from, body: e.body })),
    // The recorded right answer, for the HUD's "expected" line and for scoring the mock
    expected: c.next_action
      ? { summary: c.next_action.summary, recipient: c.next_action.recipient ?? null, channel: c.next_action.channel ?? null }
      : null,
    boundaries: c.boundaries,
  });
}
const file = `// GENERATED by scripts/build-scenarios.mjs from data/cases/delivery. Do not edit by hand.
import type { CaseScenario } from "./scenarios";

export const CASE_SCENARIOS: CaseScenario[] = ${JSON.stringify(out, null, 2)};
`;
await writeFile(path.join(ROOT, "apps/web/src/world/scenarios.data.ts"), file);
console.log(`wrote ${out.length} scenarios`);
