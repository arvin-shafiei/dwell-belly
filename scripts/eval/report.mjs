// Turns saved eval runs (runs/eval-*.json, gitignored) into the markdown committed as eval/results.md.
// Usage: node scripts/eval/report.mjs "Label for run 1=runs/eval-a.json" "Label for run 2=runs/eval-b.json" > eval/results.md
import { readFile } from "node:fs/promises";
import { OUTCOME_TO_DISPOSITION } from "./schema.mjs";

const pct = (n, d) => (d ? `${Math.round((100 * n) / d)}% (${n} of ${d})` : "n/a (no such cases in this run)");
const only = (row, disposition) => row.expected.acceptable_dispositions.length === 1 && row.expected.acceptable_dispositions[0] === disposition;
const did = (row) => OUTCOME_TO_DISPOSITION[row.result.outcome] ?? "error";

export function summarise(rows) {
  const done = rows.filter((r) => r.completed);
  const noAction = rows.filter((r) => only(r, "no_action"));
  const contactOnly = rows.filter((r) => only(r, "contact"));
  const escalateOnly = rows.filter((r) => only(r, "escalate"));
  return {
    cases: rows.length,
    score: (rows.reduce((s, r) => s + r.score, 0) / rows.length).toFixed(2),
    passing: pct(rows.filter((r) => r.pass).length, rows.length),
    completed: pct(done.length, rows.length),
    dispositionRight: pct(done.filter((r) => r.parts.disposition === 1).length, done.length),
    ownerRight: pct(done.filter((r) => r.parts.recipient === 1).length, done.length),
    actedWhenNothingOwed: pct(noAction.filter((r) => did(r) === "contact").length, noAction.length),
    overEscalated: pct(contactOnly.filter((r) => did(r) === "escalate").length, contactOnly.length),
    underEscalated: pct(escalateOnly.filter((r) => did(r) === "contact").length, escalateOnly.length),
    brokeARule: pct(rows.filter((r) => r.critical).length, rows.length),
  };
}

const LABELS = {
  cases: "Cases", score: "Mean score (0 to 1)", passing: "Passing (score 0.7 or more, no rule broken)", completed: "Completed without a system failure",
  dispositionRight: "Right kind of response (contact, escalate, or nothing)", ownerRight: "Right party addressed",
  actedWhenNothingOwed: "Sent a message when nothing was owed", overEscalated: "Escalated when a message was the answer",
  underEscalated: "Sent a message when a person had to decide", brokeARule: "Broke a must-never rule",
};

function table(runs, pick) {
  const out = [`| | ${runs.map((r) => r.label).join(" | ")} |`, `|---|${runs.map(() => "---|").join("")}`];
  for (const [key, label] of Object.entries(LABELS)) out.push(`| ${label} | ${runs.map((r) => summarise(pick(r))[key]).join(" | ")} |`);
  return out.join("\n");
}

const runs = [];
for (const arg of process.argv.slice(2)) {
  const [label, file] = arg.split("=");
  runs.push({ label, file, ...JSON.parse(await readFile(file, "utf8")) });
}
if (runs.length === 0) throw new Error('Usage: node scripts/eval/report.mjs "Label=runs/eval-x.json" ...');

const sets = [...new Set(runs.flatMap((r) => r.rows.map((row) => row.set)))];
const SET_TITLES = {
  public: "Organiser practice cases",
  generated: "Generated hard cases (internal: answer keys written by Claude, each checked blind by a second agent)",
  adversarial: "Adversarial cases (internal: written to break the agent, answer keys checked blind by a second agent)",
};
const lines = [
  "# Eval results", "",
  "Generated by `node scripts/eval/report.mjs` from saved eval runs. Not edited by hand.", "",
  "How to read this: every case is run through the agent (`npm run eval -- --agent flow`), then scored against an answer key. Disposition and channel are checked in code; whether the right party was addressed, whether the content is right and whether a must-never rule was broken are judged by a model. Each score comes from one run, and the agent is not deterministic, so small differences between runs are noise.", "",
  "## All cases", "", table(runs, (r) => r.rows), "",
  ...sets.flatMap((set) => [`## ${SET_TITLES[set] ?? set}`, "", table(runs, (r) => r.rows.filter((row) => row.set === set)), ""]),
  "## Not passing, per run", "",
];
for (const run of runs) {
  lines.push(`**${run.label}** (\`${run.file}\`)`, "");
  const failing = run.rows.filter((row) => !row.pass);
  if (failing.length === 0) lines.push("None.", "");
  for (const row of failing) {
    const why = row.critical ? `broke a rule: ${row.judgement.violations[0].rule}` : (row.judgement?.note ?? row.judgeError ?? row.result.handoff ?? "no detail");
    lines.push(`- \`${row.id}\` (${row.mutation === "none" ? "practice" : row.mutation}), ${row.score.toFixed(2)}, ${row.result.outcome}: ${String(why).replace(/\s+/g, " ").slice(0, 300)}`);
  }
  lines.push("");
}
console.log(lines.join("\n"));
