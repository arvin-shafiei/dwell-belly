// The Reality Test view: the cases `npm run reality` answered into ANSWERS/ (apps/api/src/agent/cli.ts,
// reality.ts, answers-index.ts). Each case folder is imported as an execution (origin "answers",
// dataset "reality") by importer.ts; this file reads them back and parses ANSWERS/RUNLOG.md.
// The parsers are pure; realityReport() does the I/O.
import type { Dirent } from "node:fs";
import { readdir, readFile, stat } from "node:fs/promises";
import path from "node:path";
import type { RealityCase, RealityRunlog, RealitySummary } from "../types";
import { getDb, repoRoot, type SqlValue } from "./db";

export const answersDir = () => process.env.CONSOLE_ANSWERS_DIR ?? path.join(repoRoot(), "ANSWERS");

export const CASE_FILES = ["ANSWER.md", "REASONING.md", "trace.json", "result.json"] as const;

/** Case folders under ANSWERS/: any folder holding one of the runner's files. Others are searched one level down at most twice. */
export async function answerFolders(dir: string, depth = 0): Promise<string[]> {
  let entries: Dirent[];
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  const out: string[] = [];
  for (const e of entries) {
    if (!e.isDirectory() || e.name.startsWith(".") || e.name === "node_modules") continue;
    const full = path.join(dir, e.name);
    const files = new Set(await readdir(full).catch(() => [] as string[]));
    if (CASE_FILES.some((f) => files.has(f))) out.push(full);
    else if (depth < 2) out.push(...await answerFolders(full, depth + 1));
  }
  return out.sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
}

/** The case folder named `n` under ANSWERS/, or null. Only folders found by the scan, so no path from the request is joined. */
export async function findAnswerFolder(n: string): Promise<string | null> {
  return (await answerFolders(answersDir())).find((dir) => path.basename(dir) === n) ?? null;
}

/** ANSWER.md and REASONING.md of one case, read from disk. Null when there is no such case folder. */
export async function realityFiles(n: string): Promise<{ answerMd: string | null; reasoningMd: string | null } | null> {
  const dir = await findAnswerFolder(n);
  if (!dir) return null;
  const read = (f: string) => readFile(path.join(dir, f), "utf8").catch(() => null);
  const [answerMd, reasoningMd] = await Promise.all([read("ANSWER.md"), read("REASONING.md")]);
  return { answerMd, reasoningMd };
}

const cellNum = (s: string | undefined, re: RegExp): number | null => {
  const m = s?.match(re);
  if (!m) return null;
  const n = Number(m[1]);
  return Number.isFinite(n) ? n : null;
};

/**
 * ANSWERS/RUNLOG.md as cli.ts writes it:
 *   Run <runId>. Generated by ...
 *   | Case | Result | Outcome | Time | Cost |
 *   | 7 | ok | acted | 41.2 s | $0.183 |
 * Rows whose time or cost cell is empty (kept from an earlier run, failed outside the flow) read as null.
 */
export function parseRunlog(text: string): RealityRunlog {
  const runId = text.match(/^Run (\S+?)\.?(?:\s|$)/m)?.[1] ?? null;
  const rows: RealityRunlog["rows"] = [];
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim().startsWith("|")) continue;
    const cells = line.trim().replace(/^\|/, "").replace(/\|$/, "").split("|").map((c) => c.trim());
    if (cells.length < 3) continue;
    const [caseName, result, outcome, time, cost] = cells;
    if (!caseName || caseName === "Case" || /^-+$/.test(caseName.replace(/:/g, ""))) continue;
    rows.push({
      caseName,
      result,
      outcome: outcome || null,
      seconds: cellNum(time, /^([\d.]+)\s*s$/),
      costUsd: cellNum(cost, /^\$([\d.]+)$/),
    });
  }
  return { runId, rows };
}

/** The "**Decision:** ..." line of an ANSWER.md (report.ts renderAnswer), without the markup. */
export function decisionLine(answerMd: string | null): string | null {
  const m = answerMd?.match(/^\*\*Decision:\*\*\s*(.+)$/m);
  return m ? m[1].trim() : null;
}

/** The "# Title" heading of an ANSWER.md. */
export function answerTitle(answerMd: string | null): string | null {
  const m = answerMd?.match(/^#\s+(.+)$/m);
  return m ? m[1].trim() : null;
}

type Row = Record<string, SqlValue>;

/** One imported ANSWERS/ execution row as a Reality case. */
export function realityCase(r: Row): RealityCase {
  const outcome = r.outcome === null || r.outcome === undefined ? null : String(r.outcome);
  const answerMd = r.answer_md === null || r.answer_md === undefined ? null : String(r.answer_md);
  const num = (v: SqlValue | undefined) => (v === null || v === undefined ? null : Number(v));
  return {
    n: String(r.case_id),
    caseId: String(r.case_id),
    title: (r.title === null || r.title === undefined ? null : String(r.title)) ?? answerTitle(answerMd),
    outcome,
    decision: decisionLine(answerMd),
    escalated: outcome === "escalated" || Number(r.has_card) === 1,
    failed: String(r.status) === "error" || outcome === "error",
    costUsd: num(r.cost_usd),
    durationMs: num(r.duration_ms),
    executionId: String(r.id),
  };
}

const byNumber = (a: RealityCase, b: RealityCase) => a.n.localeCompare(b.n, "en", { numeric: true });

export function summariseReality(cases: RealityCase[], runlog: RealityRunlog | null, hasIndex: boolean): RealitySummary {
  const byOutcome: Record<string, number> = {};
  for (const c of cases) {
    const k = c.outcome ?? "error";
    byOutcome[k] = (byOutcome[k] ?? 0) + 1;
  }
  const failed = cases.filter((c) => c.failed).length;
  return {
    // Cases the run was given: the run log lists every one, even those that left no folder.
    total: Math.max(cases.length, runlog?.rows.length ?? 0),
    finished: cases.length - failed,
    cases: cases.length,
    byOutcome,
    escalated: cases.filter((c) => c.escalated).length,
    failed,
    costUsd: Math.round(cases.reduce((s, c) => s + (c.costUsd ?? 0), 0) * 1e6) / 1e6,
    durationMs: cases.reduce((s, c) => s + (c.durationMs ?? 0), 0),
    runId: runlog?.runId ?? null,
    hasIndex,
  };
}

/** Every Reality case in SQLite (import first), with the run log and summary. */
export async function realityReport(): Promise<{ cases: RealityCase[]; summary: RealitySummary; runlog: RealityRunlog | null }> {
  const rows = getDb().prepare(`SELECT id, case_id, title, status, outcome, cost_usd, duration_ms, answer_md, card IS NOT NULL AS has_card
    FROM executions WHERE origin = 'answers'`).all();
  const cases = rows.map(realityCase).sort(byNumber);
  const dir = answersDir();
  const runlogText = await readFile(path.join(dir, "RUNLOG.md"), "utf8").catch(() => null);
  const runlog = runlogText === null ? null : parseRunlog(runlogText);
  const hasIndex = await stat(path.join(dir, "INDEX.md")).then((s) => s.isFile(), () => false);
  return { cases, summary: summariseReality(cases, runlog, hasIndex), runlog };
}
