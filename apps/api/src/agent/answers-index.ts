// Builds ANSWERS/INDEX.md from the saved result of each case, and checks that every case folder
// that came in has all four output files. Generated, never edited by hand.
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import type { RunResult } from "./run.ts";

export const OUTPUT_FILES = ["ANSWER.md", "REASONING.md", "trace.json", "result.json"];

const OUTCOME_WORDS: Record<string, string> = {
  acted: "Sent", asked_for_info: "Asked for information", escalated: "Held for a person",
  blocked: "Stopped by the safety check", no_action: "Nothing needed now", error: "System failure, handed to a person",
};
const cell = (s: string) => s.replace(/\|/g, "/").replace(/\s+/g, " ").trim();
const byNumber = (a: string, b: string) => a.localeCompare(b, "en", { numeric: true });
const dirs = async (dir: string) => (await readdir(dir, { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => e.name).sort(byNumber);
const exists = (file: string) => stat(file).then((s) => s.size > 0, () => false);

/** Case folders that are missing one or more output files, with the files they lack. */
export async function incomplete(casesDir: string, outDir: string): Promise<{ name: string; missing: string[] }[]> {
  const out = [];
  for (const name of await dirs(casesDir)) {
    const missing = [];
    for (const file of OUTPUT_FILES) if (!(await exists(path.join(outDir, name, file)))) missing.push(file);
    if (missing.length) out.push({ name, missing });
  }
  return out;
}

export async function buildIndex(outDir: string): Promise<{ text: string; counts: Record<string, number>; cases: number }> {
  const counts: Record<string, number> = {};
  const rows: string[] = [];
  for (const name of await dirs(outDir)) {
    const result = await readFile(path.join(outDir, name, "result.json"), "utf8").then((t) => JSON.parse(t) as RunResult, () => null);
    if (!result) {
      // A case with no saved result still has an ANSWER.md (the runner's failure answer); say so plainly.
      counts.error = (counts.error ?? 0) + 1;
      rows.push(`| [${name}](${name}/ANSWER.md) | ${OUTCOME_WORDS.error} | The run left no saved result for this case. | | |`);
      continue;
    }
    counts[result.outcome] = (counts[result.outcome] ?? 0) + 1;
    const sent = result.outbox.filter((o) => o.status === "recorded").map((o) => o.action.recipient);
    const waiting = result.outbox.filter((o) => o.status !== "recorded").length;
    const what = result.decision?.headline ?? (result.error ? `Failed at the ${result.failedAt} step.` : "");
    rows.push(`| [${name}](${name}/ANSWER.md) | ${OUTCOME_WORDS[result.outcome] ?? result.outcome} | ${cell(what)} | ${cell(sent.join("; ")) || "nobody"} | ${result.card ? cell(result.card.routeTo) : ""}${waiting ? ` (${waiting} message${waiting > 1 ? "s" : ""} not sent)` : ""} |`);
  }
  const summary = Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([k, n]) => `${n} ${(OUTCOME_WORDS[k] ?? k).toLowerCase()}`).join(", ");
  const text = [
    "# Results index", "",
    "Generated by `npm run reality` from each case's `result.json`. Not edited by hand.", "",
    `${rows.length} cases: ${summary || "none"}.`, "",
    "\"Sent\" means the message was recorded in the sandbox outbox. No live system is connected, so nothing has been delivered to or confirmed by a recipient.", "",
    "| Case | Outcome | What the desk does | Message recorded for | Handed to |", "|---|---|---|---|---|",
    ...rows, "",
  ].join("\n");
  return { text, counts, cases: rows.length };
}

export async function writeIndex(outDir: string) {
  const index = await buildIndex(outDir);
  await writeFile(path.join(outDir, "INDEX.md"), index.text);
  return index;
}
